using UnityEngine;
using UnityEngine.UI;
using UnityEngine.EventSystems;
using SprunkiKids.Data;

/// <summary>
/// Draggable bottom-tray icon for placing characters (Layer 1) or cosmetic stickers (Layer 2)
/// onto CharacterSlot targets. Supports hover pop-up scale, Mobile/Tablet multi-touch,
/// ScrollRect trays, and CanvasScaler across ScreenSpaceOverlay / ScreenSpaceCamera.
/// </summary>
public class DraggableIcon : MonoBehaviour,
    IBeginDragHandler, IDragHandler, IEndDragHandler,
    IPointerEnterHandler, IPointerExitHandler
{
    /// <summary>Fired whenever the user manually begins dragging an icon from the tray (stops Auto-Play DJ).</summary>
    public static event System.Action<DraggableIcon> OnUserDragStarted;

    [Header("Character / Sound Data")]
    [Tooltip("ScriptableObject generated by ScratchAssetImporter (takes priority over raw fields below).")]
    public CharacterSoundData characterData;

    [Tooltip("Fallback sprite if CharacterData is not assigned.")]
    public Sprite characterSprite;

    [Tooltip("Fallback audio loop if CharacterData is not assigned.")]
    public AudioClip loopAudio;

    [Header("Layer 2 Sticker Mode (Optional)")]
    [Tooltip("Enable if this draggable item is a cosmetic accessory instead of a character.")]
    public bool isStickerItem;
    public StickerAnchorType stickerAnchor = StickerAnchorType.Head;
    public Sprite stickerSprite;

    [Header("UI References & Drag Feel")]
    public Image iconImage;
    public Image backgroundBadge;
    [SerializeField] private Canvas rootCanvas;
    [SerializeField, Range(1f, 1.25f)] private float hoverScale = 1.07f;
    [SerializeField, Range(1f, 1.35f)] private float dragLiftScale = 1.15f;
    [SerializeField, Range(0.3f, 1f)] private float draggingAlpha = 0.92f;

    private RectTransform _rectTransform;
    private RectTransform _canvasRectTransform;
    private CanvasGroup _canvasGroup;
    private Transform _originalParent;
    private int _originalSiblingIndex;
    private Vector2 _originalAnchoredPosition;
    private Vector3 _originalScale = Vector3.one;
    private bool _isDragging;
    private bool _isHovered;
    private int _activePointerId = int.MinValue;

    public CharacterSoundData CharacterData => characterData;
    public bool IsSticker => isStickerItem;
    public StickerAnchorType StickerAnchor => stickerAnchor;

    public Sprite ResolvedCharacterSprite
    {
        get
        {
            if (characterData != null)
            {
                bool partyMode = AudioSyncManager.Instance != null && AudioSyncManager.Instance.IsPartyModeActive;
                return characterData.GetIdleSprite(partyMode) ?? characterData.IconSprite;
            }
            return characterSprite != null ? characterSprite : (iconImage != null ? iconImage.sprite : null);
        }
    }

    public AudioClip ResolvedAudioClip
    {
        get
        {
            if (characterData != null)
            {
                bool partyMode = AudioSyncManager.Instance != null && AudioSyncManager.Instance.IsPartyModeActive;
                return characterData.GetLoopClip(partyMode);
            }
            return loopAudio;
        }
    }

    public Sprite ResolvedStickerSprite =>
        stickerSprite != null ? stickerSprite : (characterSprite != null ? characterSprite : (iconImage != null ? iconImage.sprite : null));

    private bool _isLockedOnStage;
    private Color _badgeBaseColor = Color.white;
    private bool _badgeBaseCaptured;

    /// <summary>True while this character is on stage: the tray icon is dimmed and cannot be dragged again.</summary>
    public bool IsLockedOnStage => _isLockedOnStage;

    private void Awake()
    {
        CacheComponents();
        _originalScale = transform.localScale;
        ApplyVisualsFromData();
    }

    private void OnEnable()
    {
        CharacterSlot.OnAnySlotChanged += HandleAnySlotChanged;
        RefreshOnStageState();
    }

    private void HandleAnySlotChanged(CharacterSlot slot)
    {
        RefreshOnStageState();
    }

    private void RefreshOnStageState()
    {
        bool locked = !isStickerItem && characterData != null && CharacterSlot.IsCharacterOnStage(characterData);
        _isLockedOnStage = locked;
        ApplyLockVisual();
        if (_canvasGroup != null && !_isDragging)
        {
            _canvasGroup.blocksRaycasts = !locked;
        }
    }

    private void ApplyLockVisual()
    {
        if (backgroundBadge != null)
        {
            if (!_badgeBaseCaptured)
            {
                _badgeBaseColor = characterData != null ? characterData.ThemeColor : backgroundBadge.color;
                _badgeBaseCaptured = true;
            }

            backgroundBadge.color = _isLockedOnStage
                ? Color.Lerp(_badgeBaseColor, new Color(0.16f, 0.17f, 0.20f, 1f), 0.88f)
                : _badgeBaseColor;
        }

        if (iconImage != null)
        {
            iconImage.color = _isLockedOnStage ? new Color(0.38f, 0.38f, 0.42f, 1f) : Color.white;
        }
    }

    private void OnValidate()
    {
        CacheComponents();
        ApplyVisualsFromData();
    }

    private void OnDisable()
    {
        CharacterSlot.OnAnySlotChanged -= HandleAnySlotChanged;
        _isHovered = false;
        if (_isDragging)
        {
            RestoreToTray();
        }
        else if (_originalScale != Vector3.zero)
        {
            transform.localScale = _originalScale;
        }
    }

    public void Configure(CharacterSoundData data, Canvas canvas)
    {
        characterData = data;
        isStickerItem = false;
        if (data != null)
        {
            characterSprite = data.IdleSprite != null ? data.IdleSprite : data.IconSprite;
            loopAudio = data.MainLoopClip;
        }
        if (canvas != null)
        {
            rootCanvas = canvas.rootCanvas;
            _canvasRectTransform = rootCanvas.transform as RectTransform;
        }
        ApplyVisualsFromData();
    }

    public void ConfigureRaw(Sprite sprite, AudioClip clip, Canvas canvas, Color? badgeColor = null)
    {
        characterData = null;
        isStickerItem = false;
        characterSprite = sprite;
        loopAudio = clip;
        if (canvas != null)
        {
            rootCanvas = canvas.rootCanvas;
            _canvasRectTransform = rootCanvas.transform as RectTransform;
        }
        if (backgroundBadge != null && badgeColor.HasValue)
        {
            backgroundBadge.color = badgeColor.Value;
        }
        ApplyVisualsFromData();
    }

    public void ApplyVisualsFromData()
    {
        if (iconImage == null)
        {
            iconImage = GetComponent<Image>();
        }

        if (iconImage != null)
        {
            Sprite display = null;
            if (isStickerItem)
            {
                display = ResolvedStickerSprite;
            }
            else if (characterData != null)
            {
                display = characterData.IconSprite != null ? characterData.IconSprite : characterData.IdleSprite;
            }
            else if (characterSprite != null)
            {
                display = characterSprite;
            }

            if (display != null)
            {
                iconImage.sprite = display;
                iconImage.preserveAspect = true;
            }
        }

        if (backgroundBadge != null && characterData != null)
        {
            _badgeBaseColor = characterData.ThemeColor;
            _badgeBaseCaptured = true;
            backgroundBadge.color = _isLockedOnStage
                ? Color.Lerp(_badgeBaseColor, new Color(0.16f, 0.17f, 0.20f, 1f), 0.88f)
                : _badgeBaseColor;
        }
    }

    public void OnPointerEnter(PointerEventData eventData)
    {
        _isHovered = true;
        if (!_isDragging && !_isLockedOnStage)
        {
            transform.localScale = _originalScale * hoverScale;
        }
    }

    public void OnPointerExit(PointerEventData eventData)
    {
        _isHovered = false;
        if (!_isDragging)
        {
            transform.localScale = _originalScale;
        }
    }

    public void OnBeginDrag(PointerEventData eventData)
    {
        OnUserDragStarted?.Invoke(this);
        if (_isDragging || _isLockedOnStage) return;

        CacheComponents();
        if (rootCanvas == null) return;

        _isDragging = true;
        _activePointerId = eventData.pointerId;

        _originalParent = transform.parent;
        _originalSiblingIndex = transform.GetSiblingIndex();
        _originalAnchoredPosition = _rectTransform.anchoredPosition;

        _canvasGroup.blocksRaycasts = false;
        _canvasGroup.alpha = draggingAlpha;

        // Reparent to root Canvas so ScrollRect/RectMask2D never clips the dragged icon
        // and HorizontalLayoutGroup never gets reordered.
        transform.SetParent(rootCanvas.transform, worldPositionStays: true);
        transform.SetAsLastSibling();
        transform.localScale = _originalScale * dragLiftScale;

        UpdateDragPosition(eventData);
    }

    public void OnDrag(PointerEventData eventData)
    {
        if (!_isDragging || eventData.pointerId != _activePointerId) return;
        UpdateDragPosition(eventData);
    }

    public void OnEndDrag(PointerEventData eventData)
    {
        if (!_isDragging || eventData.pointerId != _activePointerId) return;
        RestoreToTray();
    }

    private void UpdateDragPosition(PointerEventData eventData)
    {
        if (_canvasRectTransform == null) return;

        Camera cam = rootCanvas.renderMode == RenderMode.ScreenSpaceOverlay ? null : rootCanvas.worldCamera;
        if (RectTransformUtility.ScreenPointToLocalPointInRectangle(_canvasRectTransform, eventData.position, cam, out Vector2 localPos))
        {
            _rectTransform.localPosition = localPos;
        }
    }

    private void RestoreToTray()
    {
        _isDragging = false;
        _activePointerId = int.MinValue;

        if (_canvasGroup != null)
        {
            _canvasGroup.blocksRaycasts = !_isLockedOnStage;
            _canvasGroup.alpha = 1f;
        }

        transform.localScale = (_isHovered && !_isLockedOnStage) ? _originalScale * hoverScale : _originalScale;

        if (_originalParent != null)
        {
            transform.SetParent(_originalParent, worldPositionStays: false);
            transform.SetSiblingIndex(_originalSiblingIndex);
            _rectTransform.anchoredPosition = _originalAnchoredPosition;

            if (_originalParent is RectTransform parentRect)
            {
                LayoutRebuilder.ForceRebuildLayoutImmediate(parentRect);
            }
        }
    }

    private void CacheComponents()
    {
        if (_rectTransform == null) _rectTransform = GetComponent<RectTransform>();
        if (_canvasGroup == null)
        {
            _canvasGroup = GetComponent<CanvasGroup>();
            if (_canvasGroup == null) _canvasGroup = gameObject.AddComponent<CanvasGroup>();
        }

        if (rootCanvas == null)
        {
            rootCanvas = GetComponentInParent<Canvas>();
        }

        if (rootCanvas != null)
        {
            rootCanvas = rootCanvas.rootCanvas;
            _canvasRectTransform = rootCanvas.transform as RectTransform;
        }
    }
}
